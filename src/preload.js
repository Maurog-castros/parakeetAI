'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  config: () => ipcRenderer.invoke('config'),
  suggest: (transcript) => ipcRenderer.invoke('suggest', transcript),
  translate: (text, from) => ipcRenderer.invoke('translate', text, from),
  gatewayConfig: (resetHistory, role) => ipcRenderer.invoke('gateway-config', resetHistory, role),
  practiceQuestion: (history) => ipcRenderer.invoke('practice-question', history),
  evaluatePractice: (history) => ipcRenderer.invoke('practice-evaluate', history),
  speak: (text) => ipcRenderer.invoke('tts', text),
  saveTranscriptLog: (session) => ipcRenderer.invoke('save-transcript-log', session),
  updateTranscriptLog: (session) => ipcRenderer.send('update-transcript-log', session),
  getContext: () => ipcRenderer.invoke('get-context'),
  setMode: (mode) => ipcRenderer.invoke('set-mode', mode),
  getMemory: () => ipcRenderer.invoke('get-memory'),
  summarizeMeeting: (session) => ipcRenderer.invoke('meeting-summarize', session),
  proposeInitiatives: () => ipcRenderer.invoke('memory-initiatives'),
  setMemoryItem: (id, done) => ipcRenderer.invoke('memory-set-item', id, done),
  removeMemoryItem: (id) => ipcRenderer.invoke('memory-remove-item', id),
  removeMemoryMeeting: (id) => ipcRenderer.invoke('memory-remove-meeting', id),
  saveContext: (data) => ipcRenderer.invoke('save-context', data),
  setClickThrough: (on) => ipcRenderer.send('set-click-through', on),
  setPracticeMode: (on) => ipcRenderer.send('set-practice-mode', on),
  setLayout: (mode, compactHeight) => ipcRenderer.send('set-layout', mode, compactHeight),
  setLiveShortcuts: (on) => ipcRenderer.send('set-live-shortcuts', on),
  setLiveState: (st) => ipcRenderer.send('set-live-state', st),
  onShortcut: (cb) => ipcRenderer.on('shortcut', (_e, name) => cb(name)),
  minimize: () => ipcRenderer.send('minimize'),
  quit: () => ipcRenderer.send('quit'),
  setCaptureVisible: (on) => ipcRenderer.invoke('set-capture-visible', on),
  onClickThroughChanged: (cb) => ipcRenderer.on('click-through-changed', (_e, on) => cb(!!on)),
});
